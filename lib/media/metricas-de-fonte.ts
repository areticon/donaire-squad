/** Largura de um texto, em fracoes do corpo da fonte. */
export function larguraEmCorpos(texto: string, fonte: string): number {
  const m = METRICAS[fonte];
  // Sem metrica da fonte, um palpite largo e melhor que um estreito: ele
  // encolhe a legenda a toa, e a alternativa estoura a tela.
  if (!m) return texto.length * 0.62;
  let total = 0;
  for (const ch of texto) total += m.porCaractere[ch] ?? m.media;
  return total;
}
