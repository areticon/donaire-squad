/**
 * O mapa como SVG em data URI, na cor pedida: um círculo por ponto de terra.
 * A mesma imagem serve ao navegador (<img>) e ao Satori, que lê SVG em data URI.
 */
export function mapaPontilhadoDataUri(cor: string, opacidade = 1): string {
  const passo = 10;
  const raio = 3.2;
  const circulos: string[] = [];
  MAPA_PONTILHADO.forEach((linha, y) => {
    for (let x = 0; x < linha.length; x++) {
      if (linha[x] !== "#") continue;
      circulos.push(`<circle cx="${x * passo + passo / 2}" cy="${y * passo + passo / 2}" r="${raio}"/>`);
    }
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LARGURA_DO_MAPA * passo} ${ALTURA_DO_MAPA * passo}"><g fill="${cor}" fill-opacity="${opacidade}">${circulos.join("")}</g></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}
